using System.Security.Cryptography;
using System.Text;
using HighscoreService.Domain.Exceptions;
using HighscoreService.Domain.ValueObjects;

namespace HighscoreService.Domain.Entities
{
        /// <summary>
        /// Represents a zero-touch enrolled exhibition screen server and its hashed bearer secret.
        /// </summary>
        public sealed class ScreenRegistration
        {
                /// <summary>
                /// Maximum length for a screen node identifier.
                /// </summary>
                public const int MAX_NODE_ID_LENGTH = 100;

                /// <summary>
                /// Expected length of the lowercase hex-encoded SHA-256 secret hash.
                /// </summary>
                public const int SECRET_HASH_HEX_LENGTH = 64;

                /// <summary>
                /// Initializes a new instance of the <see cref="ScreenRegistration"/> class for EF Core materialization.
                /// </summary>
                private ScreenRegistration()
                {
                }

                /// <summary>
                /// Gets the unique screen registration identifier.
                /// </summary>
                public Guid ScreenId { get; private set; }

                /// <summary>
                /// Gets the human-readable node name reported by the screen server.
                /// </summary>
                public string NodeId { get; private set; } = string.Empty;

                /// <summary>
                /// Gets the normalized IEEE 802 MAC address reported by the screen server, if available.
                /// </summary>
                public string? MacAddress { get; private set; }

                /// <summary>
                /// Gets the lowercase hex-encoded SHA-256 hash of the screen's bearer secret.
                /// </summary>
                public string SecretHash { get; private set; } = string.Empty;

                /// <summary>
                /// Gets the current approval status of the screen.
                /// </summary>
                public ScreenRegistrationStatus Status { get; private set; }

                /// <summary>
                /// Gets the UTC timestamp when the screen first enrolled.
                /// </summary>
                public DateTimeOffset CreatedAtUtc { get; private set; }

                /// <summary>
                /// Gets the UTC timestamp when an administrator approved the screen, if approved.
                /// </summary>
                public DateTimeOffset? ApprovedAtUtc { get; private set; }

                /// <summary>
                /// Gets the UTC timestamp when an administrator revoked the screen, if revoked.
                /// </summary>
                public DateTimeOffset? RevokedAtUtc { get; private set; }

                /// <summary>
                /// Creates a new <see cref="ScreenRegistration"/> in <see cref="ScreenRegistrationStatus.Pending"/> state.
                /// </summary>
                /// <param name="screenId">Unique screen identifier generated by the screen on first boot.</param>
                /// <param name="nodeId">Human-readable node identifier.</param>
                /// <param name="macAddress">Optional MAC address string.</param>
                /// <param name="rawSecret">Raw secret generated on first boot (hashed before storage).</param>
                /// <param name="createdAtUtc">Enrollment timestamp.</param>
                /// <returns>A validated <see cref="ScreenRegistration"/> entity.</returns>
                public static ScreenRegistration Enroll(
                        Guid screenId,
                        string nodeId,
                        string? macAddress,
                        string rawSecret,
                        DateTimeOffset createdAtUtc)
                {
                        // Validate identity, node name, secret entropy, and optional MAC address before hashing.
                        if (screenId == Guid.Empty)
                        {
                                throw new DomainValidationException("ScreenId must not be empty.");
                        }

                        if (string.IsNullOrWhiteSpace(nodeId))
                        {
                                throw new DomainValidationException("NodeId is required.");
                        }

                        string trimmedNodeId = nodeId.Trim();
                        if (trimmedNodeId.Length > MAX_NODE_ID_LENGTH)
                        {
                                throw new DomainValidationException($"NodeId cannot exceed {MAX_NODE_ID_LENGTH} characters.");
                        }

                        if (string.IsNullOrWhiteSpace(rawSecret) || rawSecret.Length < 16)
                        {
                                throw new DomainValidationException("Screen secret must be at least 16 characters.");
                        }

                        string? normalizedMac = string.IsNullOrWhiteSpace(macAddress)
                                ? null
                                : ValueObjects.MacAddress.Parse(macAddress).Value;

                        // Start all new registrations as Pending so an administrator must explicitly approve access.
                        return new ScreenRegistration
                        {
                                ScreenId = screenId,
                                NodeId = trimmedNodeId,
                                MacAddress = normalizedMac,
                                SecretHash = HashSecret(rawSecret),
                                Status = ScreenRegistrationStatus.Pending,
                                CreatedAtUtc = createdAtUtc.ToUniversalTime()
                        };
                }

                /// <summary>
                /// Approves the screen so it can authenticate to protected Hub endpoints.
                /// </summary>
                /// <param name="approvedAtUtc">Approval timestamp.</param>
                public void Approve(DateTimeOffset approvedAtUtc)
                {
                        // Clear any prior revocation timestamp when re-approving a screen.
                        this.Status = ScreenRegistrationStatus.Approved;
                        this.ApprovedAtUtc = approvedAtUtc.ToUniversalTime();
                        this.RevokedAtUtc = null;
                }

                /// <summary>
                /// Revokes the screen so its bearer credential is immediately rejected.
                /// </summary>
                /// <param name="revokedAtUtc">Revocation timestamp.</param>
                public void Revoke(DateTimeOffset revokedAtUtc)
                {
                        // Mark revoked in UTC so token validation rejects subsequent requests immediately.
                        this.Status = ScreenRegistrationStatus.Revoked;
                        this.RevokedAtUtc = revokedAtUtc.ToUniversalTime();
                }

                /// <summary>
                /// Verifies a presented raw secret against the stored SHA-256 hash using constant-time comparison.
                /// </summary>
                /// <param name="rawSecret">Presented secret.</param>
                /// <returns><see langword="true"/> when the secret matches; otherwise <see langword="false"/>.</returns>
                public bool VerifySecret(string rawSecret)
                {
                        if (string.IsNullOrWhiteSpace(rawSecret))
                        {
                                return false;
                        }

                        // Compare SHA-256 digests in fixed time to avoid timing side channels.
                        byte[] presentedHashBytes = SHA256.HashData(Encoding.UTF8.GetBytes(rawSecret));
                        byte[] storedHashBytes = Convert.FromHexString(this.SecretHash);
                        return CryptographicOperations.FixedTimeEquals(presentedHashBytes, storedHashBytes);
                }

                private static string HashSecret(string rawSecret)
                {
                        // Store lowercase hex SHA-256 so raw secrets are never persisted in SQL Server.
                        byte[] hashBytes = SHA256.HashData(Encoding.UTF8.GetBytes(rawSecret));
                        return Convert.ToHexStringLower(hashBytes);
                }
        }
}

