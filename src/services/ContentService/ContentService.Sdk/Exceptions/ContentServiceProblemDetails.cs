using System.Text.Json;
using System.Text.Json.Serialization;

namespace ContentService.Sdk.Exceptions;

/// <summary>
/// Deserialization contract for RFC 7807 ProblemDetails payloads returned by <c>ContentService.Api</c>.
/// </summary>
public sealed class ContentServiceProblemDetails
{
        /// <summary>
        /// Gets or sets a URI reference identifying the problem type.
        /// </summary>
        public string? Type { get; set; }

        /// <summary>
        /// Gets or sets a short, human-readable summary of the problem type.
        /// </summary>
        public string? Title { get; set; }

        /// <summary>
        /// Gets or sets the HTTP status code generated by the origin server.
        /// </summary>
        public int? Status { get; set; }

        /// <summary>
        /// Gets or sets a human-readable explanation specific to this occurrence of the problem.
        /// </summary>
        public string? Detail { get; set; }

        /// <summary>
        /// Gets or sets a URI reference identifying the specific occurrence of the problem.
        /// </summary>
        public string? Instance { get; set; }

        /// <summary>
        /// Gets or sets additional extension members included in the problem payload.
        /// </summary>
        [JsonExtensionData]
        public Dictionary<string, JsonElement>? Extensions { get; set; }
}

